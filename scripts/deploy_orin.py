import hashlib
import io
import json
from pathlib import Path
import subprocess
import sys
import tarfile
import time
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'outputs'))
from g1_config import PROJECT, HOST, REMOTE_ROOT, REMOTE_TOOLS, REMOTE_PYTHON, XR_REPO, robot_settings, ssh

