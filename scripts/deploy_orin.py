  relative=pathlib.PurePosixPath(member.name)
  if not member.isfile() or relative.is_absolute() or '..' in relative.parts: raise RuntimeError('Invalid archive member')
  target=stage/str(relative); target.parent.mkdir(parents=True,exist_ok=True)
  with target.open('wb') as out: out.write(archive.extractfile(member).read())
