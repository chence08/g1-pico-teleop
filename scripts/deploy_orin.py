def payload():
    model=XR_REPO/'assets/g1'
    if not (model/'g1_body29_hand14.urdf').is_file():
        raise RuntimeError('Pinned G1 assets missing; run workstation bootstrap or set XR_TELEOPERATE_REPO')
    files={p.name:p.read_bytes() for p in (PROJECT/'outputs').glob('*.py')}
    files['install_inspire_access.sh']=(PROJECT/'outputs/install_inspire_access.sh').read_bytes()
    files['g1_body29_hand14.urdf']=(model/'g1_body29_hand14.urdf').read_bytes()
    for p in sorted((model/'meshes').rglob('*')):
        if p.is_file(): files['meshes/'+p.relative_to(model/'meshes').as_posix()]=p.read_bytes()
    files['deployment.json']=(json.dumps(robot_settings(),indent=2)+'\n').encode()
    files['deployment-manifest.json']=(json.dumps({'schema':1,'sha256':{k:hashlib.sha256(v).hexdigest() for k,v in files.items()}},indent=2)+'\n').encode()
    return files

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--apply',action='store_true');args=parser.parse_args()
    files=payload()
    print(json.dumps({'host':HOST,'destination':REMOTE_TOOLS,'robot_python':REMOTE_PYTHON,'files':len(files),'bytes':sum(map(len,files.values())),'apply':args.apply},indent=2),flush=True)
    if not args.apply: print('Plan only. Add --apply to deploy after stopping B and recorders.');return
    subprocess.run(ssh(['python3','-c',CHECK,REMOTE_PYTHON]),check=True,timeout=20)
    blob=io.BytesIO()
    with tarfile.open(fileobj=blob,mode='w') as archive:
        for name,data in files.items():
            info=tarfile.TarInfo(name);info.size=len(data);info.mode=0o644;archive.addfile(info,io.BytesIO(data))
    subprocess.run(ssh(['python3','-c',INSTALL,REMOTE_ROOT,str(time.time_ns())]),input=blob.getvalue(),check=True,timeout=180)
    print('Source/assets installed; no services started. Existing Orin Python/SDK/camera runtime preserved.')
if __name__=='__main__': main()
